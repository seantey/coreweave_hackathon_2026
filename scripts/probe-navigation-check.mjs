import assert from 'node:assert/strict';
import * as THREE from 'three';
import { ProbeNavigation } from '../src/probe-navigation.ts';
const navigation = new ProbeNavigation();
const wall = new THREE.Mesh(new THREE.PlaneGeometry(10,10), new THREE.MeshBasicMaterial());
wall.position.z = -2;
navigation.rebuild([wall]);
let result = navigation.move(new THREE.Vector3(), new THREE.Vector3(0,0,-10));
assert.equal(result.blocked,true);
assert.ok(result.position.z > -1.89 && result.position.z < -1.8, 'Stops before a thin wall without tunneling');
result = navigation.move(new THREE.Vector3(0,0,-4), new THREE.Vector3(0,0,10));
assert.equal(result.blocked,true);
assert.ok(result.position.z < -2.11, 'Back faces also block movement');
result = navigation.move(new THREE.Vector3(), new THREE.Vector3(2,0,0));
assert.equal(result.blocked,false);
assert.equal(result.position.x,2);
wall.position.x = 20;
navigation.rebuild([wall]);
assert.equal(navigation.move(new THREE.Vector3(),new THREE.Vector3(0,0,-4)).blocked,false,'Rebuild respects transformed geometry');
navigation.rebuild([]);
assert.equal(navigation.move(new THREE.Vector3(),new THREE.Vector3(1,0,0)).blocked,true,'Missing collider does not imply clear');
console.log('Probe navigation: thin walls, both sides, clear path, revised transforms, missing geometry passed');
